    <h1>Política de privacidad de SIGCOM</h1>
    <p class="muted">Última actualización: 12 de octubre de 2026</p>

    <p>SIGCOM (Sistema de Gestión Comercial) es una aplicación de uso interno de Grupo Santacruz
        (Agropecuaria Santacruz, Carnes Frías Santacruz y Montería TAT Agropecuaria). Solo pueden usarla
        empleados y colaboradores con un usuario creado por la empresa; no permite registrarse desde la app.</p>

    <h2>Datos que tratamos</h2>
    <ul>
        <li><strong>Datos del usuario:</strong> nombre, número de documento (cédula), correo electrónico corporativo, rol y compañías asignadas.</li>
        <li><strong>Datos comerciales:</strong> clientes (razón social, NIT, sucursal, dirección, ciudad, teléfono, correo), pedidos, cotizaciones, cartera, listas de precios e inventario.</li>
        <li><strong>Ubicación del cliente:</strong> la dirección, barrio y ciudad que el vendedor registra manualmente para la entrega. La app <strong>no</strong> accede al GPS del teléfono.</li>
        <li><strong>Datos técnicos:</strong> un token de sesión guardado de forma cifrada en el dispositivo.</li>
    </ul>

    <h2>Para qué los usamos</h2>
    <ul>
        <li>Tomar, aprobar, despachar y hacer seguimiento de pedidos.</li>
        <li>Consultar ventas, presupuestos, cartera y disponibilidad de productos.</li>
        <li>Enviar cotizaciones, estados de cartera y reportes por correo a solicitud del usuario.</li>
    </ul>

    <h2>Con quién se comparten</h2>
    <p>Los datos se procesan en los servidores de Grupo Santacruz y en su sistema contable (Siesa).
        No se venden ni se comparten con terceros con fines publicitarios. La app no contiene publicidad ni rastreadores.</p>

    <h2>Seguridad</h2>
    <p>Toda la comunicación viaja cifrada (HTTPS). El acceso requiere usuario y contraseña, y los permisos dependen del rol asignado por la empresa.</p>

    <h2>Conservación y eliminación</h2>
    <p>Los datos se conservan mientras exista la relación laboral o comercial y según las obligaciones legales de la empresa.
        Para desactivar o eliminar una cuenta, o para consultar, corregir o suprimir datos personales (Ley 1581 de 2012),
        escribe a <a href="mailto:sistemas@carnessantacruz.co">sistemas@carnessantacruz.co</a>.</p>

    <h2>Contacto</h2>
    <p>Grupo Santacruz · Área de Sistemas · <a href="mailto:sistemas@carnessantacruz.co">sistemas@carnessantacruz.co</a></p>
